export const SIMBOLOS = filas.map(([caracter, nombre, categoria, terminos]) => ({
  caracter,
  nombre,
  categoria,
  terminos,
}));

export const normalizar = (valor) => String(valor || '')
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .trim();

export function buscarSimbolos(consulta = '', categoria = 'todas', usados = []) {
  const q = normalizar(consulta);
  const cat = categoria && categoria !== 'todas' ? categoria : null;
  const cuenta = new Map(usados.map((item) => [item.caracter, Math.max(0, Number(item.cantidad) || 0)]));

  const lista = SIMBOLOS.filter((s) => {
    if (cat && s.categoria !== cat) return false;
    if (!q) return true;
    return normalizar(`${s.caracter} ${s.nombre} ${s.categoria} ${s.terminos}`).includes(q);
  });

  return lista.sort((a, b) => (cuenta.get(b.caracter) || 0) - (cuenta.get(a.caracter) || 0)
    || SIMBOLOS.indexOf(a) - SIMBOLOS.indexOf(b));
}

export function registrarSimbolo(usados, caracter) {
  const mapa = new Map(usados.map((item) => [item.caracter, Math.max(0, Number(item.cantidad) || 0)]));
  mapa.set(caracter, (mapa.get(caracter) || 0) + 1);
  return [...mapa].map(([glyph, cantidad]) => ({ caracter: glyph, cantidad }))
    .sort((a, b) => b.cantidad - a.cantidad)
    .slice(0, 12);
}
